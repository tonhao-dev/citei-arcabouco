import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

export const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const SPECS_DIR = join(ROOT, 'specs');
export const STEERING_DIR = join(ROOT, '.kiro', 'steering');
export const INDEX_PATH = join(ROOT, 'INDEX.md');

export const ID_PATTERN = /\b(ARCH|ADR|STD|SEC|AI)-[0-9]{3}\b/g;
export const CITATION_PATTERN = /\[((?:ARCH|ADR|STD|SEC|AI)-[0-9]{3})\]/g;

export const PREFIX_TO_TYPE: Record<string, string> = {
  ARCH: 'architecture',
  ADR: 'adr',
  SEC: 'security',
  STD: 'standard',
  AI: 'ai-guideline',
};

export interface Spec {
  path: string;
  data: Record<string, unknown>;
  body: string;
}

export function toPosix(path: string): string {
  return path.split(sep).join('/');
}

export function rel(path: string): string {
  return toPosix(relative(ROOT, path));
}

export function listMarkdown(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listMarkdown(full));
    else if (name.endsWith('.md')) out.push(full);
  }
  return out;
}

export function splitFrontMatter(text: string): { data: Record<string, unknown> | null; body: string; error?: string } {
  const normalized = text.replace(/\r\n/g, '\n');
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(normalized);
  if (!match) return { data: null, body: normalized };
  try {
    const data = parse(match[1], { schema: 'core' }) as Record<string, unknown>;
    return { data: data ?? {}, body: match[2] };
  } catch (err) {
    return { data: null, body: match[2], error: (err as Error).message };
  }
}

export function loadSpecs(): Spec[] {
  return listMarkdown(SPECS_DIR).map((path) => {
    const { data, body } = splitFrontMatter(readFileSync(path, 'utf8'));
    return { path, data: data ?? {}, body };
  });
}

export function renderIndex(specs: Spec[]): string {
  const rows = specs
    .filter((s) => typeof s.data.spec_id === 'string')
    .sort((a, b) => String(a.data.spec_id).localeCompare(String(b.data.spec_id)))
    .map((s) => {
      const d = s.data;
      const tags = Array.isArray(d.tags) ? d.tags.join(', ') : '';
      const path = rel(s.path);
      return `| ${d.spec_id} | [${d.title}](${path}) | ${d.spec_type} | ${d.status} | ${tags} |`;
    });
  return [
    '<!-- Generated by `npm run index`. Do not edit by hand. -->',
    '',
    '# Spec index',
    '',
    'Resolve a spec ID to its file. Only `approved` specs are rules.',
    '',
    '| ID | Title | Type | Status | Tags |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}
